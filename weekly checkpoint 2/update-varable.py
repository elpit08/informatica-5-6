def main():
#Augmented Assignment Operator
    score = 10
    score += 10
    print(score)

#Substraction Assignment Operator
    #x= x-y
    #x-=y
    scor = 100
    scor -= 15
    print(scor)

#Multiplication Assignment Operator
    sco = 50
    sco *= 2
    print(sco)

#Division Assignment Operator
    sc = 100
    sc /=5
    print(int(sc))

#Modular Assignment Operator
    s = 10
    s %= 4
    print(s)


if __name__=="__main__":
    main()
